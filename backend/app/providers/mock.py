"""Deterministic offline provider.

Produces schema-valid output for every agent so the whole system runs without API keys. All
text is clearly labelled as mock output; it never invents businesses, people or contact details
and only quotes figures it receives in the business-data snapshot.
"""

from __future__ import annotations

import json
import re
from typing import Any

from app.providers.base import LLMRequest, LLMResponse, ProviderError

MOCK_NOTE = "Generated by the offline mock provider; no AI model was called."
_MAX_ROUTED = 3


def _words(text: str) -> str:
    return " ".join(text.lower().split())


def _short(text: str, n: int = 90) -> str:
    text = " ".join(text.split())
    return text if len(text) <= n else text[: n - 1] + "…"


class MockLLMProvider:
    name = "mock"

    def default_model(self) -> str:
        return "mock-1"

    def generate(self, request: LLMRequest) -> LLMResponse:
        builders = {
            "CEOPlan": self._plan,
            "CEOSynthesis": self._synthesis,
            "SpecialistOutput": self._specialist,
        }
        builder = builders.get(request.schema_name)
        if builder is None:
            raise ProviderError(f"Mock provider has no generator for {request.schema_name}")
        data = builder(request)
        text = json.dumps(data)
        prompt_chars = len(request.system) + sum(len(m.content) for m in request.messages)
        return LLMResponse(
            provider=self.name,
            model=request.model or self.default_model(),
            data=data,
            raw_text=text,
            prompt_tokens=max(1, prompt_chars // 4),
            completion_tokens=max(1, len(text) // 4),
            estimated_cost=None,
            notes=[MOCK_NOTE],
        )

    # -- CEO planning ------------------------------------------------------------------------

    def _plan(self, request: LLMRequest) -> dict[str, Any]:
        ctx = request.mock_context
        text: str = ctx.get("request", "")
        lowered = _words(text)
        agents: list[dict[str, Any]] = ctx.get("available_agents", [])

        chosen: list[dict[str, Any]] = []
        # An explicit "... to the Sales Agent" wins over keyword routing.
        for agent in agents:
            name = agent["name"].lower()
            if name in lowered or name.replace(" agent", "") + " agent" in lowered:
                if re.search(r"\b(delegate|assign|ask|send this)\b", lowered):
                    chosen = [agent]
                    break
        if not chosen:
            # Most keyword hits first; ties go to the agent mentioned earliest in the request.
            scored: list[tuple[int, int, dict[str, Any]]] = []
            for agent in agents:
                positions = [lowered.find(k) for k in agent.get("keywords", []) if k in lowered]
                if positions:
                    scored.append((-len(positions), min(positions), agent))
            scored.sort(key=lambda t: (t[0], t[1]))
            chosen = [a for _, _, a in scored[:_MAX_ROUTED]]
        if not chosen:
            fallback = next((a for a in agents if a["key"] == "business_strategy"), None)
            chosen = [fallback] if fallback else agents[:1]

        subtasks = [
            {
                "agent_key": a["key"],
                "title": f"{a['name']}: {_short(text, 70)}",
                "instructions": (
                    f"The Founder asked: \"{text.strip()}\". Handle the part of this request that "
                    f"falls under your role ({a['name']}). Work only from the data provided; do "
                    "not invent businesses or contact details."
                ),
                "priority": "NORMAL",
            }
            for a in chosen
        ]
        names = ", ".join(a["name"] for a in chosen)
        task_type = (chosen[0]["key"] if chosen else "general") + "_request"
        return {
            "understanding": f"The Founder wants: {_short(text, 160)}",
            "task_type": task_type,
            "reply": f"[Mock] I have delegated this to: {names}.",
            "subtasks": subtasks,
        }

    def _synthesis(self, request: LLMRequest) -> dict[str, Any]:
        results: list[dict[str, Any]] = request.mock_context.get("results", [])
        lines = []
        next_steps: list[str] = []
        for r in results:
            status = r.get("status", "")
            if r.get("summary"):
                titles = ", ".join(r.get("deliverables") or []) or "no deliverables"
                state = " (awaiting your approval)" if status == "AWAITING_APPROVAL" else ""
                lines.append(f"• {r['agent']}{state}: {titles}")
            else:
                lines.append(f"• {r['agent']}: did not finish ({status.lower()}).")
            if status == "AWAITING_APPROVAL":
                next_steps.append(f"Review the approval request from {r['agent']}.")
        next_steps.append("Open the task details to read each deliverable in full.")
        return {
            "summary": "[Mock] Results from the team:\n" + "\n".join(lines),
            "next_steps": next_steps,
        }

    # -- Specialists -------------------------------------------------------------------------

    def _specialist(self, request: LLMRequest) -> dict[str, Any]:
        ctx = request.mock_context
        key: str = ctx.get("agent_key", "agent")
        name: str = ctx.get("agent_name", "Agent")
        instructions: str = ctx.get("instructions", "")
        data: dict[str, Any] = ctx.get("context", {})
        can_propose: bool = ctx.get("can_propose", False)
        # Delegated tasks carry the Founder's original words; prefer them for a readable topic.
        topic = _short(str(data.get("founder_request") or instructions), 120)

        builder = getattr(self, f"_spec_{key}", self._spec_generic)
        deliverables, recommendations, actions = builder(topic, data)
        if not can_propose:
            actions = []
        return {
            "summary": f"[Mock] {name} prepared {len(deliverables)} draft(s) for \"{topic}\".",
            "deliverables": deliverables,
            "recommendations": recommendations,
            "proposed_actions": actions,
            "assumptions": [
                "This is deterministic mock output for offline use; connect an LLM provider for real analysis."
            ],
            "open_questions": ["Which client or segment should this be tailored to?"],
        }

    @staticmethod
    def _spec_generic(topic: str, data: dict[str, Any]):
        return (
            [{"title": "Working notes", "kind": "report",
              "content": f"Scope: {topic}\n\n1. Clarify the goal and audience.\n2. Gather the data needed.\n3. Draft, review, then request approval for anything external."}],
            ["Confirm the scope before work starts."],
            [],
        )

    @staticmethod
    def _spec_business_strategy(topic: str, data: dict[str, Any]):
        return (
            [{"title": "Market and positioning outline", "kind": "plan",
              "content": (
                  f"Request: {topic}\n\nTarget segment: owner-operated local service businesses "
                  "with 5–50 staff.\nCommon pain points to verify: slow lead response, no "
                  "follow-up process, weak website conversion.\nOffer hypothesis: done-for-you "
                  "lead capture + follow-up automation, monthly retainer.\n\nNext: validate "
                  "with 5 discovery calls before building assets."
              )}],
            ["Validate the offer with real prospect conversations before scaling outreach.",
             "Track lead response time as the core success metric."],
            [],
        )

    @staticmethod
    def _spec_sales(topic: str, data: dict[str, Any]):
        prospects = data.get("prospects") or []
        if prospects:
            rows = "\n".join(f"- {p.get('company_name', 'Unnamed')}: {p.get('notes', 'no notes')}" for p in prospects[:20])
            content = f"Prospects supplied ({len(prospects)}):\n{rows}"
        else:
            content = (
                "No prospect records were supplied, so no businesses are named here.\n\n"
                "To build the list: import a CSV of real businesses (Prospects, Phase 3) or "
                "export one from a licensed data source, then re-run this task.\n\n"
                "Qualification checklist: service area match, website present, reviews volume, "
                "visible booking/lead form, response to a test enquiry."
            )
        return (
            [{"title": "Prospect research report", "kind": "report", "content": content},
             {"title": "Proposal outline", "kind": "plan",
              "content": "1. Problem observed\n2. Proposed fix\n3. Deliverables and timeline\n4. Investment\n5. Next step"}],
            ["Qualify each prospect against the checklist before outreach."],
            [],
        )

