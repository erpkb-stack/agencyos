"""Landing-page HTML generation and validation.

The page is a single self-contained HTML file (inline CSS, no JavaScript, no external requests) so
it can be previewed safely and downloaded for hosting. Every value is HTML-escaped.
"""

from __future__ import annotations

import re
from html import escape
from typing import Any

FIELD_NAME = re.compile(r"^[a-z][a-z0-9_]{0,39}$")
FIELD_TYPES = {"text", "email", "tel", "select", "textarea", "number"}
PLACEHOLDER = re.compile(r"\[[^\]]{2,160}\]")
MAX_RECOMMENDED_FIELDS = 7

