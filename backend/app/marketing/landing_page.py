def _field_html(f: dict[str, Any]) -> str:
    name = escape(f["name"])
    label = escape(f.get("label") or f["name"])
    req = ' required' if f.get("required") else ""
    star = ' <span class="req" aria-hidden="true">*</span>' if f.get("required") else ""
    ftype = f.get("type", "text")
    if ftype == "select":
        options = "".join(f"<option>{escape(str(o))}</option>" for o in f.get("options") or [])
        control = f'<select id="f-{name}" name="{name}"{req}><option value="">Choose…</option>{options}</select>'
    elif ftype == "textarea":
        control = f'<textarea id="f-{name}" name="{name}"{req}></textarea>'
    else:
        auto = {"email": "email", "tel": "tel", "full_name": "name"}.get(ftype if ftype in ("email", "tel") else f["name"], "")
        auto_attr = f' autocomplete="{auto}"' if auto else ""
        control = f'<input id="f-{name}" name="{name}" type="{escape(ftype)}"{auto_attr}{req}>'
    return f'<label for="f-{name}">{label}{star}</label>{control}'


def render(funnel: Any, *, preview: bool = False) -> str:
    config = funnel.form_config or {}
    copy = config.get("copy") or {}
    business = copy.get("business_name") or funnel.name
    phone = copy.get("phone_display")
    benefits = "".join(f"<li>{escape(b)}</li>" for b in copy.get("benefits") or [])
    fields = "".join(_field_html(f) for f in funnel.lead_fields or [])
    action = escape(config.get("action_url") or "#")
    banner = ('<div class="preview-banner">Preview generated by AgencyOS. The form does not submit '
              'anywhere until a form handler is connected.</div>') if preview else ""
    proof = f'<p class="proof">{escape(copy["proof"])}</p>' if copy.get("proof") else ""
    phone_html = f'<a class="phone" href="tel:{escape(re.sub(r"[^0-9+]", "", phone))}">{escape(phone)}</a>' if phone else ""
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(copy.get("headline") or funnel.name)}</title>
<meta name="description" content="{escape(copy.get("subheadline") or "")}">
<style>{CSS}</style>
</head>
<body>
{banner}
<header><div class="wrap"><span class="brand">{escape(business)}</span>{phone_html}</div></header>
<main class="hero"><div class="wrap grid">
<section>
<h1>{escape(copy.get("headline") or funnel.name)}</h1>
<p class="sub">{escape(copy.get("subheadline") or "")}</p>
<ul class="benefits">{benefits}</ul>
{proof}
</section>
<!-- Connect this form to a form handler or CRM before publishing. -->
<form method="post" action="{action}">
<h2>{escape(funnel.call_to_action or "Get in touch")}</h2>
{fields}
<button type="submit">{escape(config.get("submit_label") or funnel.call_to_action or "Submit")}</button>
<p class="consent">{escape(config.get("consent_text") or "")}</p>
</form>
</div></main>
<footer><div class="wrap">&copy; {escape(business)}</div></footer>
</body>
</html>
"""


def issue(level: str, message: str) -> dict[str, str]:
    return {"level": level, "message": message}


def validate(funnel: Any) -> list[dict[str, str]]:
    """Form and content rules. Errors block an approval request; warnings are advice."""
    issues: list[dict[str, str]] = []
    fields = funnel.lead_fields or []
    config = funnel.form_config or {}
    copy = config.get("copy") or {}

    if not fields:
        issues.append(issue("error", "The lead form has no fields"))
    names = [f.get("name", "") for f in fields]
    for f in fields:
        name = f.get("name", "")
        if not FIELD_NAME.match(name):
            issues.append(issue("error", f"Field name '{name}' must be lowercase letters, digits or _"))
        if not (f.get("label") or "").strip():
            issues.append(issue("error", f"Field '{name}' needs a label"))
        if f.get("type", "text") not in FIELD_TYPES:
            issues.append(issue("error", f"Field '{name}' has an unsupported type"))
        if f.get("type") == "select" and not f.get("options"):
            issues.append(issue("error", f"Dropdown '{name}' has no options"))
    for dup in sorted({n for n in names if names.count(n) > 1}):
        issues.append(issue("error", f"Field name '{dup}' is used more than once"))
    types = {f.get("type") for f in fields}
    if fields and not ({"email", "tel"} & types):
        issues.append(issue("error", "Collect at least an email or a phone number so the lead can be contacted"))
    if fields and not any(f.get("required") for f in fields if f.get("type") in ("email", "tel")):
        issues.append(issue("warning", "No contact field is required; leads may arrive with no way to reply"))
    if len(fields) > MAX_RECOMMENDED_FIELDS:
        issues.append(issue("warning", f"{len(fields)} fields; forms with more than {MAX_RECOMMENDED_FIELDS} convert worse"))
    if not (funnel.call_to_action or "").strip():
        issues.append(issue("error", "Add a call to action"))
    if not (copy.get("headline") or "").strip():
        issues.append(issue("error", "Add a headline"))
    if ({"email", "tel"} & types) and not (config.get("consent_text") or "").strip():
        issues.append(issue("error", "Add consent text explaining how contact details will be used"))
    texts = [copy.get("headline"), copy.get("subheadline"), copy.get("proof"), copy.get("business_name"),
             copy.get("phone_display"), config.get("consent_text"), *(copy.get("benefits") or [])]
    leftover = sorted({m for t in texts if t for m in PLACEHOLDER.findall(t)})
    if leftover:
        issues.append(issue("error", "Replace placeholder text before publishing: " + ", ".join(leftover)))
    return issues


def mobile_checks(html: str) -> list[dict[str, Any]]:
    """Static responsiveness checks on the generated HTML."""
    checks = [
        ("Viewport meta tag", bool(re.search(r'<meta name="viewport" content="width=device-width', html))),
        ("Single-column layout under 760px", "@media (max-width:760px)" in html),
        ("Inputs use 16px text (no zoom on iOS)", "font-size:16px" in html),
        ("Tap targets at least 44px tall", "min-height:44px" in html and "min-height:48px" in html),
        ("No fixed widths wider than a phone", not re.search(r"(?<!max-)width:\s*\d{4,}px", html)),
        ("Content width is capped", "max-width:1040px" in html),
        ("No scripts or external resources", "<script" not in html and not re.search(r'(src|href)="https?://', html)),
    ]
    return [{"check": name, "passed": ok} for name, ok in checks]
